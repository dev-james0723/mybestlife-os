const localizedKnowledgeUi = createLocaleCopyMap<KnowledgeUiCopy>(en, knowledgeLocaleOverrides);

export function getKnowledgeUiCopy(locale: AppLocale): KnowledgeUiCopy {
  return localizedKnowledgeUi[locale] ?? localizedKnowledgeUi.en;
}

export function formatKnowledgeDate(locale: AppLocale, date: string): string {
  return new Intl.DateTimeFormat(locale, {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(new Date(date));
}

/** Calendar date + clock time in the viewer's local timezone, ordered for `locale`. */
export function formatKnowledgeLocalDateTime(locale: AppLocale, date: string): string {
  const d = new Date(date);
  if (Number.isNaN(d.getTime())) return "—";
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(d);
}

export function formatKnowledgeRelativeAge(locale: AppLocale, date: string): string {
  const d = new Date(date);
  if (Number.isNaN(d.getTime())) return "";
  return formatDistanceToNow(d, { addSuffix: true, locale: getDateFnsLocale(locale) });
}
