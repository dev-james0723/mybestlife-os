function unique(values) {
  return Array.from(new Set(values));
}

function toImportAlias(sourceName) {
  return `${sourceName
    .split("-")
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("")}Component`;
}

function rewriteComponentSource(contents) {
  const rewritten = contents
    .replaceAll('from "motion/react"', 'from "framer-motion"')
    .replaceAll("from 'motion/react'", "from 'framer-motion'");

  if (rewritten.startsWith('"use client";')) return rewritten;
  return `"use client";\n\n${rewritten}`;
}

function sortByAssetId(entries) {
  return [...entries].sort(([a], [b]) => a.localeCompare(b));
}

async function main() {
  const sourceIcons = unique(Object.values(ASSET_TO_SOURCE_ICON)).sort();
  await rm(OUTPUT_COMPONENT_DIR, { force: true, recursive: true });
  await mkdir(OUTPUT_COMPONENT_DIR, { recursive: true });

  await copyFile(
    path.join(SOURCE_ICONS_DIR, "types.ts"),
    path.join(OUTPUT_COMPONENT_DIR, "types.ts"),
  );

  for (const sourceName of sourceIcons) {
    const sourceFile = path.join(SOURCE_ICONS_DIR, `${sourceName}.tsx`);
    const contents = await readFile(sourceFile, "utf8");
    await writeFile(
      path.join(OUTPUT_COMPONENT_DIR, `${sourceName}.tsx`),
      rewriteComponentSource(contents),
      "utf8",
    );
  }

  await copyFile(
    path.join(SOURCE_ROOT, "LICENSE"),
    path.join(OUTPUT_COMPONENT_DIR, "LICENSE"),
  );

  await writeFile(
    path.join(OUTPUT_COMPONENT_DIR, "README.md"),
    `# ${PACK_NAME}\n\nVendored animated icon components from itshover/itshover for the My Life OS navigation icon pack picker.\n\n- Source: https://github.com/itshover/itshover\n- Pack id: \`${PACK_ID}\`\n- Generated by: \`app/scripts/generate-itshover-icon-pack-components.mjs\`\n- Import rewrite: \`motion/react\` -> \`framer-motion\`\n\nOnly the mapped navigation components are vendored here.\n`,
    "utf8",
  );

  const imports = sourceIcons
    .map((sourceName) => {
      return `import ${toImportAlias(sourceName)} from "@/components/liquid-icons/animated/hover-intent/${sourceName}";`;
    })
    .join("\n");

  const mappings = sortByAssetId(Object.entries(ASSET_TO_SOURCE_ICON))
    .map(([assetId, sourceName]) => {
      return `  ${JSON.stringify(assetId)}: ${toImportAlias(sourceName)},`;
    })
    .join("\n");

  await writeFile(
    OUTPUT_COMPONENT_REGISTRY,
    `import type { ForwardRefExoticComponent, RefAttributes } from "react";\n${imports}\n\nexport type ItshoverAnimatedIconHandle = {\n  startAnimation: () => void;\n  stopAnimation: () => void;\n};\n\ntype ItshoverAnimatedIconComponent = ForwardRefExoticComponent<\n  Record<string, unknown> & RefAttributes<ItshoverAnimatedIconHandle>\n>;\n\nexport const ITSHOVER_ICON_COMPONENTS = {\n${mappings}\n} satisfies Partial<Record<string, ItshoverAnimatedIconComponent>>;\n`,
    "utf8",
  );

  console.log(
    `Generated ${sourceIcons.length} ${PACK_NAME} components for ${Object.keys(ASSET_TO_SOURCE_ICON).length} navigation assets.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
