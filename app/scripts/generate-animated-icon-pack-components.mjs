function toImportAlias(fileName, exportName) {
  return `${fileName
    .split("-")
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("")}${exportName}`;
}

function parseExportedComponentName(contents, sourceName) {
  const aliasedExportMatch = contents.match(/export\s+\{\s*\w+\s+as\s+(\w+)\s*\};/);
  if (aliasedExportMatch) return aliasedExportMatch[1];

  const namedExportMatch = contents.match(/export\s+\{\s*(\w+)\s*\};/);
  if (namedExportMatch) return namedExportMatch[1];

  const exportedConstMatch = contents.match(/export\s+const\s+(\w+)\s*=/);
  if (exportedConstMatch) return exportedConstMatch[1];

  const displayNameMatch = contents.match(/(\w+)\.displayName\s*=/);
  if (displayNameMatch) return displayNameMatch[1];

  {
    throw new Error(`Could not find exported component name in ${sourceName}.tsx`);
  }
}

function rewriteComponentSource(contents) {
  return contents
    .replaceAll('from "motion/react"', 'from "framer-motion"')
    .replaceAll("from 'motion/react'", "from 'framer-motion'");
}

function unique(values) {
  return Array.from(new Set(values));
}

function sortBySourceName(entries) {
  return [...entries].sort(([a], [b]) => a.localeCompare(b));
}

async function main() {
  const sourceIcons = unique(Object.values(ASSET_TO_SOURCE_ICON)).sort();
  await rm(OUTPUT_COMPONENT_DIR, { force: true, recursive: true });
  await mkdir(OUTPUT_COMPONENT_DIR, { recursive: true });

  const importedComponents = new Map();

  for (const sourceName of sourceIcons) {
    const sourceFile = path.join(SOURCE_ICONS_DIR, `${sourceName}.tsx`);
    const contents = await readFile(sourceFile, "utf8");
    const exportName = parseExportedComponentName(contents, sourceName);
    const alias = toImportAlias(sourceName, exportName);
    importedComponents.set(sourceName, { exportName, alias });

    await writeFile(
      path.join(OUTPUT_COMPONENT_DIR, `${sourceName}.tsx`),
      rewriteComponentSource(contents),
      "utf8",
    );
  }

  await writeFile(
    path.join(OUTPUT_COMPONENT_DIR, "README.md"),
    `# ${PACK_NAME}\n\nVendored animated icon components from pqoqubbw/icons for the My Life OS navigation icon pack picker.\n\n- Source: https://github.com/pqoqubbw/icons\n- Pack id: \`${PACK_ID}\`\n- Generated by: \`app/scripts/generate-animated-icon-pack-components.mjs\`\n- Import rewrite: \`motion/react\` -> \`framer-motion\`\n\nOnly the mapped navigation components are vendored here.\n`,
    "utf8",
  );

  await copyFile(
    path.join(SOURCE_ROOT, "LICENSE"),
    path.join(OUTPUT_COMPONENT_DIR, "LICENSE"),
  );

  const imports = sourceIcons
    .map((sourceName) => {
      const { exportName, alias } = importedComponents.get(sourceName);
      return `import { ${exportName} as ${alias} } from "@/components/liquid-icons/animated/kinetic-linework/${sourceName}";`;
    })
    .join("\n");

  const mappings = sortBySourceName(Object.entries(ASSET_TO_SOURCE_ICON))
    .map(([assetId, sourceName]) => {
      const { alias } = importedComponents.get(sourceName);
      return `    ${JSON.stringify(assetId)}: ${alias} as AnimatedIconComponent,`;
    })
    .join("\n");

  await writeFile(
    OUTPUT_COMPONENT_REGISTRY,
    `import type { ForwardRefExoticComponent, HTMLAttributes, RefAttributes } from "react";\nimport type { AnimatedIconPackId } from "@/lib/liquid-icons/animated-icon-pack-metadata";\nimport { ITSHOVER_ICON_COMPONENTS } from "@/lib/liquid-icons/itshover-icon-pack-components";\n${imports}\n\nexport type AnimatedIconHandle = {\n  startAnimation: () => void;\n  stopAnimation: () => void;\n};\n\nexport type AnimatedIconProps = HTMLAttributes<HTMLDivElement> & {\n  size?: number;\n};\n\nexport type AnimatedIconComponent = ForwardRefExoticComponent<\n  AnimatedIconProps & RefAttributes<AnimatedIconHandle>\n>;\n\nexport const ANIMATED_ICON_COMPONENTS: Record<\n  AnimatedIconPackId,\n  Partial<Record<string, AnimatedIconComponent>>\n> = {\n  "${PACK_ID}": {\n${mappings}\n  },\n  "hover-intent": ITSHOVER_ICON_COMPONENTS as Partial<Record<string, AnimatedIconComponent>>,\n};\n\nexport function getAnimatedIconPackAssetComponent(\n  iconPack: AnimatedIconPackId,\n  assetId: string,\n): AnimatedIconComponent | undefined {\n  return ANIMATED_ICON_COMPONENTS[iconPack]?.[assetId];\n}\n`,
    "utf8",
  );

  await writeFile(
    OUTPUT_METADATA,
    `export type AnimatedIconPackId = "${PACK_ID}" | "hover-intent";\n\nexport type AnimatedIconPackMeta = {\n  id: AnimatedIconPackId;\n  packageName: string;\n  name: string;\n  description: string;\n  sourceRepo: string;\n};\n\nexport const ANIMATED_ICON_PACKS: AnimatedIconPackMeta[] = [\n  {\n    id: "${PACK_ID}",\n    packageName: "pqoqubbw-icons",\n    name: "${PACK_NAME}",\n    description: "${PACK_DESCRIPTION}",\n    sourceRepo: "https://github.com/pqoqubbw/icons",\n  },\n  {\n    id: "hover-intent",\n    packageName: "itshover",\n    name: "Hover Intent",\n    description: "Intentional React/Motion icons from It's Hover with crisp interaction-driven motion.",\n    sourceRepo: "https://github.com/itshover/itshover",\n  },\n];\n\nconst ANIMATED_ICON_PACK_IDS = new Set<AnimatedIconPackId>(\n  ANIMATED_ICON_PACKS.map((pack) => pack.id),\n);\n\nexport function isAnimatedIconPackId(value: unknown): value is AnimatedIconPackId {\n  return typeof value === "string" && ANIMATED_ICON_PACK_IDS.has(value as AnimatedIconPackId);\n}\n`,
    "utf8",
  );

  console.log(
    `Generated ${sourceIcons.length} animated components for ${Object.keys(ASSET_TO_SOURCE_ICON).length} navigation assets.`,
  );
}

